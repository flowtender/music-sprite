_SCHEMA_TYPES = {
    "string": {"type": "string"},
    "integer": {"type": "integer"},
    "array of strings": {"type": "array", "items": {"type": "string"}},
}

RESPONSE_SCHEMA = {
    "type": "object",
    "properties": {
        "reasoning": {"type": "string"},
        **{name: {"anyOf": [_SCHEMA_TYPES[_kind(name)], {"type": "null"}]} for name in ANSWER_KEYS},
        "confidence": {"type": "number"},
    },
    "required": ["reasoning", *ANSWER_KEYS, "confidence"],
    "additionalProperties": False,
}

THINK_BLOCK = re.compile(r"<think>.*?</think>", re.DOTALL)

# The upload's metadata goes to the model whole, since other sites (Bandcamp, SoundCloud, ...) report different
# things than YouTube does; only what is bulky or describes the file format rather than the music is dropped.
DROPPED_KEYS = BULKY_INFO_KEYS | {
    "thumbnail", "storyboards", "fragments", "filename", "epoch", "format", "format_id", "format_note", "ext",
    "protocol", "resolution", "acodec", "vcodec", "abr", "vbr", "asr", "tbr", "audio_channels", "dynamic_range",
    "container", "filesize", "filesize_approx", "language_preference", "quality", "source_preference", "preference",
    "has_drm", "stretched_ratio", "aspect_ratio", "width", "height", "fps", "video_ext", "audio_ext",
}


def _text(value: object) -> str | None:
    return (value.strip() or None) if isinstance(value, str) else None


def _year(value: object) -> int | None:
    """Models without schema enforcement answer "1998" or 0 now and then."""
    if isinstance(value, str) and value.strip().isdigit():
        value = int(value)
    if isinstance(value, int) and not isinstance(value, bool) and 1000 <= value <= 9999:
        return value
    return None


def _count(value: object) -> int | None:
    """A track number or track count, with the same leniency as _year."""
    if isinstance(value, str) and value.strip().isdigit():
        value = int(value)
    if isinstance(value, int) and not isinstance(value, bool) and 0 < value < 1000:
        return value
    return None


def _names(value: object, limit: int) -> list[str] | None:
    """Distinct names; a lone string (from a model without schema enforcement) is one name."""
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list):
        return None
    names: list[str] = []
    for item in value:
        name = _text(item)
        if name and name.casefold() not in {known.casefold() for known in names}:
            names.append(name)
    return names[:limit] or None


def _confidence(value: object) -> float:
    try:
        number = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 0.0
    return 0.0 if math.isnan(number) else min(max(number, 0.0), 1.0)


def _present(facts: dict) -> dict:
    return {key: value for key, value in facts.items() if value not in (None, "", [], {})}


def trim_upload(info: dict, description_chars: int) -> dict:
    trimmed = _present(portable_info(info, DROPPED_KEYS))
    if isinstance(trimmed.get("description"), str):
        trimmed["description"] = trimmed["description"][:description_chars]
    return trimmed


def _release_facts(index: int, meta: TrackMetadata) -> dict:
    release = meta.release
    position = f"{release.track_number}/{release.track_total}" if release.track_number and release.track_total else None
    return _present(
        {
            "index": index,
            "artist": meta.artist,
            "title": meta.title,
            "album": meta.album,
            "album_artist": meta.album_artist,
            "date": release.release_date or meta.year,
            "original_date": release.original_date,
            "track": position,
            "disc": release.disc_number if release.disc_total and release.disc_total > 1 else None,
            "label": release.label,
            "catalog_number": release.catalog_number,
            "country": release.country,
            "status": release.status,
            "release_types": release.types,
            "genres": meta.genres,
            "length_seconds": round(meta.length_seconds) if meta.length_seconds else None,
            "credits": {role: names[:5] for role, names in release.credits.items()},
        }
    )


def _audio_facts(findings: Findings) -> dict | None:
    audio = findings.audio
    if audio is None:
        return None
    return _present(
        {
            "bpm": audio.bpm,
            "key": audio.key,
            "vocals": audio.vocals,
            "genre_guesses": [[name, round(probability, 2)] for name, probability in audio.genres],
            "moods": audio.moods,
            "instruments": audio.instruments,
            "scores": {name: round(score, 2) for name, score in audio.scores.items()},
            "loudness_lufs": None if audio.loudness is None else round(audio.loudness, 1),
        }
    )


class LlmClient:
    def __init__(self, http: httpx.AsyncClient, config: LlmConfig, known_publishers: frozenset[str]):
        self._http = http
        self._config = config
        self._known_publishers = known_publishers

    @property
    def enabled(self) -> bool:
        return bool(self._config.model)

    async def resolve(self, info: dict, findings: Findings) -> LlmVerdict:
        """Answers every field from everything the other sources found. Raises LookupUnavailable."""
        facts = self._facts(info, findings)
        started = time.monotonic()
        try:
            response = await self._http.post(
                f"{self._config.base_url}/chat/completions",
                json=self._request_body(facts),
                headers=self._headers(),
                timeout=self._config.timeout_seconds,
            )
            response.raise_for_status()
            payload = response.json()
            parsed = self._parse(payload["choices"][0]["message"]["content"])
        except (httpx.HTTPError, KeyError, IndexError, ValueError) as error:
            log.warning("LLM metadata lookup failed: %s", error)
            self._log_call(info, started, None, None, str(error))
            raise LookupUnavailable("llm") from error

        self._log_call(info, started, payload.get("usage"), parsed, None)
        return LlmVerdict(
            model=self._config.model,
            answers=self._answers(parsed, len(findings.releases)),
            reasoning=_text(parsed.get("reasoning")) or "",
            confidence=_confidence(parsed.get("confidence")),
        )

    @staticmethod
    def _answers(parsed: dict, release_count: int) -> dict[str, str | int | list[str]]:
        """Only answers that make sense for their field count."""
        answers: dict[str, str | int | list[str]] = {}
        for name in ANSWER_KEYS:
            value = parsed.get(name)
            if name == "year":
                value = _year(value)
            elif name == RELEASE:
                value = value if valid_index(value, release_count) else None
            elif name in NUMBER_FIELDS:
                value = _count(value)
            elif name in NAME_LISTS:
                value = _names(value, MAX_GENRES if name == GENRES else MAX_NAMES)
            else:
                value = _text(value)
            if value is not None:
                answers[name] = value
        return answers

    def _facts(self, info: dict, findings: Findings) -> dict:
        upload = findings.upload
        return _present(
            {
                "publisher_channels": sorted(self._known_publishers),
                "upload": trim_upload(info, self._config.description_chars),
                "heuristic_guess": _present(
                    {
                        "artist": upload.artist,
                        "title": upload.title,
                        "album": upload.album,
                        "year": upload.year,
                        "genres": upload.genres,
                        "confidence": upload.confidence,
                    }
                ),
                "musicbrainz": [_release_facts(index, release) for index, release in enumerate(findings.releases)],
                "audio_analysis": _audio_facts(findings),
            }
        )

    def _request_body(self, facts: dict) -> dict:
        body = {
            "model": self._config.model,
            "temperature": 0,
            "max_tokens": 1000,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": json.dumps(facts, ensure_ascii=False)},
            ],
        }
        if self._config.json_mode == "schema":
            body["response_format"] = {
                "type": "json_schema",
                "json_schema": {"name": "track_metadata", "strict": True, "schema": RESPONSE_SCHEMA},
            }
        elif self._config.json_mode == "object":
            body["response_format"] = {"type": "json_object"}
        return body

    def _headers(self) -> dict:
        if self._config.api_key:
            return {"Authorization": f"Bearer {self._config.api_key}"}
        return {}

    @staticmethod
    def _parse(content: str) -> dict:
        """The first JSON object in the reply. Chat models wrap it in prose or code fences despite instructions."""
        content = THINK_BLOCK.sub("", content)
        decoder = json.JSONDecoder()
        for found in re.finditer(r"\{", content):
            try:
                parsed, _ = decoder.raw_decode(content, found.start())
            except ValueError:
                continue
            if isinstance(parsed, dict):
                return parsed
        raise ValueError("no JSON object in model output")

    def _log_call(self, info: dict, started: float, usage: dict | None, parsed: dict | None, error: str | None):
        if not self._config.call_log:
            return
        record = {
            "time": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "model": self._config.model,
            "base_url": self._config.base_url,
            "seconds": round(time.monotonic() - started, 2),
            "usage": usage,
            "url": info.get("webpage_url"),
            "result": parsed,
            "error": error,
        }
        try:
            self._config.call_log.parent.mkdir(parents=True, exist_ok=True)
            with self._config.call_log.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")
        except OSError as os_error:
            log.warning("could not write LLM call log: %s", os_error)
